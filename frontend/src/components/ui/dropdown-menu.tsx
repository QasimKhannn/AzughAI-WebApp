// Simple dropdown component for common use cases
interface SimpleDropdownProps extends VariantProps<typeof dropdownTriggerVariants> {
  value?: string | number
  onValueChange?: (value: string | number) => void
  placeholder?: string
  options: { label: string; value: string | number }[]
  className?: string
  disabled?: boolean
}

const SimpleDropdown = React.forwardRef<
  React.ElementRef<typeof DropdownMenuTrigger>,
  SimpleDropdownProps
>(({ variant, value, onValueChange, placeholder, options, className, disabled, ...props }, ref) => {
  const selectedOption = options.find(option => option.value === value)

  return (
    <DropdownMenu>
      <DropdownMenuTrigger
        ref={ref}
        className={cn(dropdownTriggerVariants({ variant }), className)}
        disabled={disabled}
        {...props}
      >
        <span className="truncate">
          {selectedOption ? selectedOption.label : placeholder}
        </span>
        <ChevronDown className="h-3 w-3 opacity-60" />
      </DropdownMenuTrigger>
      <DropdownMenuContent variant={variant} className="min-w-[var(--radix-dropdown-menu-trigger-width)]">
        {options.map((option) => (
          <DropdownMenuItem
            key={option.value}
            variant={variant}
            onClick={() => onValueChange?.(option.value)}
            className={cn(
              selectedOption?.value === option.value && variant === "glass" && "bg-white/20"
            )}
          >
            {option.label}
          </DropdownMenuItem>
        ))}
      </DropdownMenuContent>
    </DropdownMenu>
  )
})
SimpleDropdown.displayName = "SimpleDropdown"

